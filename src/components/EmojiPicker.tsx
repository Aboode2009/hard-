interface EmojiPickerProps {
  selectedEmoji: string;
  onEmojiSelect: (emoji: string) => void;
  color?: string;
  isArabic?: boolean;
}

export const EmojiPicker = ({ selectedEmoji, onEmojiSelect, color = "#14b8a6", isArabic = false }: EmojiPickerProps) => {
  const [activeCategory, setActiveCategory] = useState("smileys");
  const [open, setOpen] = useState(false);

  const handleEmojiClick = (emoji: string) => {
    onEmojiSelect(emoji);
    setOpen(false);
  };

  return (
    <Popover open={open} onOpenChange={setOpen}>
      <PopoverTrigger asChild>
        <button
          className="w-16 h-16 rounded-xl flex items-center justify-center text-3xl border-2 border-dashed border-border transition-all hover:border-primary"
          style={{ backgroundColor: `${color}20` }}
        >
          {selectedEmoji || "⭐"}
        </button>
      </PopoverTrigger>
      <PopoverContent className="w-80 p-0" align="start">
        {/* Category Tabs */}
        <div className="flex border-b border-border overflow-x-auto">
          {Object.keys(EMOJI_CATEGORIES).map((category) => (
            <button
              key={category}
              onClick={() => setActiveCategory(category)}
              className={cn(
                "flex-shrink-0 p-2 text-xl transition-colors",
                activeCategory === category 
                  ? "bg-primary/10 border-b-2 border-primary" 
                  : "hover:bg-muted"
              )}
              title={isArabic ? CATEGORY_LABELS[category].ar : CATEGORY_LABELS[category].en}
            >
              {CATEGORY_LABELS[category].icon}
            </button>
          ))}
        </div>
        
        {/* Emoji Grid */}
        <ScrollArea className="h-64">
          <div className="grid grid-cols-8 gap-1 p-2">
            {EMOJI_CATEGORIES[activeCategory as keyof typeof EMOJI_CATEGORIES].map((emoji, index) => (
              <button
                key={`${emoji}-${index}`}
                onClick={() => handleEmojiClick(emoji)}
                className={cn(
                  "w-8 h-8 flex items-center justify-center text-xl rounded-md transition-colors hover:bg-muted",
                  selectedEmoji === emoji && "bg-primary/20 ring-2 ring-primary"
                )}
              >
                {emoji}
              </button>
            ))}
          </div>
        </ScrollArea>
      </PopoverContent>
    </Popover>
  );
};
